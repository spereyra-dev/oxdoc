#!/usr/bin/env python3
"""Create and validate a versioned benchmark bundle for a GitHub Release.

The measurements themselves are intentionally produced by the existing Criterion
and peak-memory workflows. This script records the inputs and environment needed
to interpret a particular release's measurements and packages their raw output.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import platform
import shutil
import subprocess
import tempfile
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
REQUIRED_FILES = ("README.md", "metadata.json", "peak-memory.md", "criterion")


def command_output(command: list[str]) -> str:
    return subprocess.run(
        command,
        cwd=REPO_ROOT,
        check=True,
        text=True,
        stdout=subprocess.PIPE,
    ).stdout.strip()


def create_bundle(tag: str, output: Path, memory_report: Path, criterion: Path) -> None:
    if not tag.startswith("v") or len(tag) == 1:
        raise ValueError("--tag must be a release tag beginning with v")
    if not memory_report.is_file():
        raise ValueError(f"peak-memory report not found: {memory_report}")
    if not criterion.is_dir():
        raise ValueError(f"Criterion output directory not found: {criterion}")

    output.mkdir(parents=True, exist_ok=True)
    shutil.copy2(memory_report, output / "peak-memory.md")
    shutil.copytree(criterion, output / "criterion", dirs_exist_ok=True)
    metadata = {
        "format_version": 1,
        "release_tag": tag,
        "commit": command_output(["git", "rev-parse", "HEAD"]),
        "generated_at_utc": dt.datetime.now(dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "environment": {
            "platform": platform.platform(),
            "machine": platform.machine(),
            "python": platform.python_version(),
            "rustc": command_output(["rustc", "--version"]),
            "cargo": command_output(["cargo", "--version"]),
            "github_runner": os.environ.get("RUNNER_NAME"),
            "github_runner_os": os.environ.get("RUNNER_OS"),
        },
        "commands": [
            "cargo bench --locked -p oxdoc-core --bench throughput",
            "python3 scripts/peak-memory-baselines.py --no-build --binary target/release/oxdoc --iterations 3 --output peak-memory.md",
        ],
        "contents": {
            "criterion": "Raw Criterion output, including estimates and sample data.",
            "peak-memory.md": "Median peak-RSS measurements for synthetic CLI workloads.",
        },
    }
    (output / "metadata.json").write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    (output / "README.md").write_text(bundle_readme(tag), encoding="utf-8")
    validate_bundle(output)


def bundle_readme(tag: str) -> str:
    return f"""# oxdoc {tag} benchmark evidence

This bundle is the benchmark evidence produced for release `{tag}`. It contains
raw Criterion output for in-process parser throughput and a three-sample,
synthetic-fixture peak-memory report for the release CLI.

Run the commands in `metadata.json` from the tagged commit to repeat the
workflow. The fixtures are generated by repository scripts, so no external or
redistributed Office files are required.

Results are evidence for the recorded environment, not a cross-machine
leaderboard. Compare releases only when the runner/OS, architecture, tooling,
commands, and fixture parameters are materially equivalent. The competitor
workbench is deliberately not included: its optional tools and differing output
semantics require separately recorded local versions and commands.
"""


def validate_bundle(bundle: Path) -> None:
    missing = [name for name in REQUIRED_FILES if not (bundle / name).exists()]
    if missing:
        raise ValueError("benchmark bundle is missing: " + ", ".join(missing))
    metadata = json.loads((bundle / "metadata.json").read_text(encoding="utf-8"))
    for key in ("format_version", "release_tag", "commit", "environment", "commands"):
        if not metadata.get(key):
            raise ValueError(f"benchmark metadata is missing {key}")
    if metadata["format_version"] != 1:
        raise ValueError("unsupported benchmark metadata format")
    if not metadata["release_tag"].startswith("v"):
        raise ValueError("benchmark metadata release_tag must begin with v")
    if len(metadata["commit"]) != 40:
        raise ValueError("benchmark metadata commit must be a full Git SHA")
    if not any((bundle / "criterion").rglob("estimates.json")):
        raise ValueError("Criterion output contains no estimates.json files")


def self_test() -> None:
    with tempfile.TemporaryDirectory() as temporary:
        bundle = Path(temporary)
        (bundle / "criterion" / "case" / "new").mkdir(parents=True)
        (bundle / "criterion" / "case" / "new" / "estimates.json").write_text("{}")
        (bundle / "README.md").write_text("test")
        (bundle / "peak-memory.md").write_text("test")
        (bundle / "metadata.json").write_text(
            json.dumps(
                {
                    "format_version": 1,
                    "release_tag": "v0.0.0",
                    "commit": "0" * 40,
                    "environment": {"platform": "test"},
                    "commands": ["test"],
                }
            )
        )
        validate_bundle(bundle)
        (bundle / "criterion" / "case" / "new" / "estimates.json").unlink()
        try:
            validate_bundle(bundle)
        except ValueError:
            return
        raise AssertionError("validation accepted a bundle without Criterion estimates")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tag", help="Release tag, for example v0.1.0")
    parser.add_argument("--output", type=Path, help="Directory to create")
    parser.add_argument("--memory-report", type=Path, help="Peak-memory Markdown report")
    parser.add_argument("--criterion", type=Path, help="Criterion output directory")
    parser.add_argument("--validate", type=Path, help="Validate an existing bundle")
    parser.add_argument("--self-test", action="store_true", help="Run validation smoke tests")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return 0
    if args.validate:
        validate_bundle(args.validate)
        return 0
    if not all((args.tag, args.output, args.memory_report, args.criterion)):
        parser.error("--tag, --output, --memory-report, and --criterion are required")
    create_bundle(args.tag, args.output, args.memory_report, args.criterion)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
